local ns = T.LoadAddon()
local Money = ns.Economy.Money

T.Case("nil is never zero", function()
  local value, reason = Money.Normalize(nil)
  T.Eq(value, nil)
  T.Eq(reason, "missing")
end)

T.Case("normalize rejects non-finite, negative, fractional, huge and opaque values", function()
  T.Eq(select(2, Money.Normalize(0 / 0)), "not_finite")
  T.Eq(select(2, Money.Normalize(math.huge)), "not_finite")
  T.Eq(select(2, Money.Normalize(-1)), "negative")
  T.Eq(select(2, Money.Normalize(1.5)), "fractional")
  T.Eq(select(2, Money.Normalize(2 ^ 60)), "out_of_range")
  T.Eq(select(2, Money.Normalize({})), "unsupported_type")
  T.Eq(select(2, Money.Normalize("100")), "unsupported_type")
  T.Eq(Money.Normalize(12345), 12345)
end)

T.Case("integer division rounds as requested", function()
  T.Eq(Money.DivFloor(10000, 20), 500)
  T.Eq(Money.DivCeil(10000, 20), 500)
  T.Eq(Money.DivFloor(1001, 20), 50)
  T.Eq(Money.DivCeil(1001, 20), 51)
  T.Eq(Money.DivCeil(Money.MAX_SAFE, 3), 3002399751580331)
  T.Eq(Money.DivFloor(5, 0), nil)
end)

T.Case("shares round costs up and revenues down", function()
  T.Eq(Money.ShareUp(12000, 500), 600)
  T.Eq(Money.ShareUp(11053, 500), 553)
  T.Eq(Money.ShareDown(11053, 500), 552)
  T.Eq(Money.ShareUp(1, 1), 1)
  T.Eq(Money.ShareDown(1, 1), 0)
end)

T.Case("multiplication and addition guard the safe range", function()
  T.Eq(Money.Mul(50, 20), 1000)
  T.Eq(Money.Mul(Money.MAX_SAFE, 2), nil)
  T.Eq(Money.Add(Money.MAX_SAFE, 1), nil)
  T.Eq(Money.Mul(nil, 2), nil)
end)

T.Case("format keeps unknown visible", function()
  T.Eq(Money.Format(nil), "?")
  T.Eq(Money.Format(12345), "1g 23s 45c")
  T.Eq(Money.Format(45), "45c")
  T.Eq(Money.Format(-150), "-1s 50c")
  T.Eq(Money.ToBasisPoints(0.05), 500)
end)
